  const lines = [{ e: route.emoji, t: `${route.name} 완주 — ${route.tagline}` }];
  if (a.B1 && a.B4) lines.push({ e: '📈', t: `내 일 속도 ${a.B1}점 · 회사 기여 ${a.B4}점${hi(a.B1) && lo(a.B4) ? ' → 숫자의 역설 목격' : ''}` });
  if (a.C6) lines.push({ e: '⏳', t: `AI 도입 후 업무량: ${a.C6}` });
  if (a.X1) lines.push({ e: '🚫', t: `AI를 쓰지 않는 이유: ${a.X1}` });
  if (a.D3) lines.push({ e: '⚔️', t: `깃발 꽂을 땅: ${a.D3}` });
